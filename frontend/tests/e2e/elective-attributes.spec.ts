import { expect, test } from "@playwright/test";

test("browse Social Sciences I or II on one page, change matching mode and clear filters", async ({page}) => {
  test.setTimeout(60000);
  await page.goto("/login");
  await page.getByLabel("University email", {exact:true}).fill("recommendations-attributes@mail.aub.edu");
  await page.getByLabel("Password", {exact:true}).fill("test-verified-password");
  await page.getByRole("button", {name:"Log in",exact:true}).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.goto("/electives/preferences");
  await expect(page.getByRole("heading", {name:"Find your next elective"})).toBeVisible();
  await expect(page.getByLabel("Interests", {exact:true})).not.toBeVisible();
  await page.getByLabel("Browse semester", {exact:true}).selectOption("202720");
  await page.getByLabel("Search attributes", {exact:true}).fill("social sciences");
  await page.getByRole("checkbox", {name:"Social Sciences I",exact:true}).check();
  await page.getByRole("checkbox", {name:"Social Sciences II",exact:true}).check();
  await expect(page.getByRole("checkbox", {name:"Science",exact:true})).toHaveCount(0);
  let requests = 0;
  page.on("request", request => {if(request.url().endsWith("/api/electives/recommendations") && request.method() === "POST") requests++;});
  await page.getByRole("button", {name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("3 matching courses found.", {timeout:20000});
  expect(requests).toBe(1);
  const results = page.getByRole("region", {name:"Matching elective courses"});
  await expect(results.locator("summary")).toHaveCount(3);
  await expect(results.locator("article")).toHaveCount(0);
  await expect(results.getByText("SOCI 200",{exact:true})).toBeVisible();
  await expect(results.getByText("SOCI 201",{exact:true})).toBeVisible();
  await expect(results.getByText("SOCI 203",{exact:true})).toHaveCount(1);
  await results.locator("summary").filter({hasText:"SOCI 200"}).click();
  await expect(results.locator("article")).toHaveCount(1);
  await expect(results.getByRole("link",{name:"Add to schedule",exact:true})).toBeVisible();
  await results.locator("summary").filter({hasText:"SOCI 200"}).click();
  await expect(results.locator("article")).toHaveCount(0);
  await page.locator("summary").filter({hasText:"More filters"}).click();
  await page.getByLabel("Department",{exact:true}).selectOption("Social Sciences");
  await expect(page.getByRole("checkbox",{name:"Social Sciences I",exact:true})).toBeChecked();
  await expect(page.getByRole("status")).toHaveText("3 matching courses found.");
  await page.getByLabel("Instructor",{exact:true}).fill("Nobody matching");
  await page.getByRole("button",{name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("0 matching courses found.");
  await page.getByLabel("Instructor",{exact:true}).fill("");
  await page.getByRole("button",{name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("3 matching courses found.");
  await page.setViewportSize({width:375,height:812});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:"/tmp/campusconnect-elective-attributes-mobile.png"});
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:"/tmp/campusconnect-elective-attributes-desktop.png"});
  await page.setViewportSize({width:375,height:812});
  await page.getByLabel("Match courses with",{exact:true}).selectOption("all");
  await expect(page.locator("article")).toHaveCount(0);
  await page.getByRole("button", {name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("1 matching course found.");
  await page.getByRole("button", {name:"Remove Social Sciences I",exact:true}).click();
  await page.getByRole("button", {name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("2 matching courses found.");
  await page.getByRole("button", {name:"Clear attributes",exact:true}).click();
  await page.getByRole("button", {name:"Show courses",exact:true}).click();
  await expect(page.getByRole("status")).toHaveText("3 matching courses found.");
  await page.getByLabel("Department",{exact:true}).selectOption("");
  await expect(page.getByRole("status")).toHaveText("4 matching courses found.");
  await page.getByLabel("Browse semester",{exact:true}).selectOption("202710");
  await expect(page.locator("article")).toHaveCount(0);
  await expect(page.getByRole("button",{name:/^Remove /})).toHaveCount(0);
  await page.getByLabel("Search attributes", {exact:true}).fill("no-such-attribute");
  await expect(page.getByText("No matching attributes. Try a shorter search.")).toBeVisible();
});
