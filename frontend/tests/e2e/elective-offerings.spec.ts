import { expect, test } from "@playwright/test";

test("private semester and section choices persist, filter recommendations and can be cleared", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("University email", { exact: true }).fill("recommendations-offerings@mail.aub.edu");
  await page.getByLabel("Password", { exact: true }).fill("test-verified-password");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.goto("/electives/preferences");
  await page.getByLabel("Interests", { exact: true }).fill("operating");
  await page.getByLabel("Academic goals", { exact: true }).fill("Learn systems");
  await expect(page.getByLabel("Instructors", { exact: true })).toBeDisabled();
  await page.getByLabel("Semester", { exact: true }).selectOption("202720");
  await page.getByLabel("Instructors", { exact: true }).fill("Spring Instructor");
  await page.getByLabel("Required course attributes", { exact: true }).fill("Writing in the Discipline");
  await page.getByLabel("Monday", { exact: true }).check();
  await page.getByLabel("Wednesday", { exact: true }).check();
  await page.getByLabel("Earliest class start", { exact: true }).fill("09:00");
  await page.getByLabel("Latest class end", { exact: true }).fill("11:45");
  await page.getByRole("button", { name: "Save preferences" }).click();
  await expect(page.getByRole("status")).toHaveText("Preferences saved.");
  await page.reload();
  await expect(page.getByLabel("Semester", { exact: true })).toHaveValue("202720");
  await expect(page.getByLabel("Instructors", { exact: true })).toHaveValue("Spring Instructor");
  await expect(page.getByLabel("Required course attributes", { exact: true })).toHaveValue("Writing in the Discipline");
  await expect(page.getByLabel("Monday", { exact: true })).toBeChecked();
  await expect(page.getByLabel("Wednesday", { exact: true })).toBeChecked();
  await expect(page.getByLabel("Latest class end", { exact: true })).toHaveValue("11:45");
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/campusconnect-elective-offering-preferences.png", fullPage: true });
  await page.getByRole("link", { name: "View elective recommendations →" }).click();
  await page.getByRole("button", { name: "Get recommendations" }).click();
  await expect(page.getByRole("status")).toHaveText("1 recommendation found.");
  const matches = page.getByRole("region", { name: "Matching sections for CMPS 240" });
  await expect(matches).toContainText("Spring 2026-2027 · 2 matching sections");
  await expect(matches).toContainText("09:00–10:15");
  await expect(matches).toContainText("10:30–11:45");
  await expect(matches).not.toContainText("12:00–13:15");
  await expect(matches).not.toContainText("Fall Instructor");
  const repeat=page.waitForResponse(r=>r.url().endsWith("/api/electives/recommendations")&&r.request().method()==="POST");
  await page.getByRole("button",{name:"Get recommendations"}).click();
  const cached=await repeat;
  expect(cached.headers()["server-timing"]).toContain('catalogue_cache;desc="hit"');
  expect(cached.headers()["server-timing"]).toContain("auth;dur=");
  await expect(page.getByRole("status")).toHaveText("1 recommendation found.");

  await expect(page.getByRole("link", { name: "CMPS 240 · Operating Systems", exact: true })).toHaveAttribute("href", "/courses/CMPS-240?semester=202720");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/campusconnect-elective-offering-results.png", fullPage: true });
  await page.getByRole("link", { name: "Edit your preferences" }).click();
  await page.getByLabel("Monday", { exact: true }).uncheck();
  await page.getByLabel("Wednesday", { exact: true }).uncheck();
  await page.getByLabel("Tuesday", { exact: true }).check();
  await page.getByRole("button", { name: "Save preferences" }).click();
  await expect(page.getByRole("status")).toHaveText("Preferences saved.");
  await page.getByRole("link", { name: "View elective recommendations →" }).click();
  await page.getByRole("button", { name: "Get recommendations" }).click();
  await expect(page.getByRole("status")).toHaveText("0 recommendations found.");
  await page.getByRole("link", { name: "Edit your preferences" }).click();
  await page.getByLabel("Semester", { exact: true }).selectOption("");
  await page.getByRole("button", { name: "Save preferences" }).click();
  await expect(page.getByRole("status")).toHaveText("Preferences saved.");
  await page.reload();
  await expect(page.getByLabel("Semester", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Instructors", { exact: true })).toHaveValue("");
  await page.getByRole("link", { name: "View elective recommendations →" }).click();
  await page.getByRole("button", { name: "Get recommendations" }).click();
  await expect(page.getByRole("status")).toHaveText("1 recommendation found.");
  await expect(page.getByRole("region", { name: "Matching sections for CMPS 240" })).toHaveCount(0);
});

